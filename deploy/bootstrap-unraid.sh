#!/bin/bash
# Bootstrap aion2-tracker on an Unraid server.
#
# Idempotent: safe to re-run. It will not overwrite an existing .env or
# database, and it detects whether docker compose is available, falling back to
# plain `docker run` if the Compose Manager plugin is not installed.
#
#   curl -fsSL https://raw.githubusercontent.com/doarjo/aion2-tracker/main/deploy/bootstrap-unraid.sh | bash
#
# or copy it across and run: bash bootstrap-unraid.sh

set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/doarjo/aion2-tracker.git}"
APPDATA="${APPDATA:-/mnt/user/appdata/aion2-tracker}"
SRC="$APPDATA/src"
ENV_FILE="$SRC/.env"
HOST_PORT="${HOST_PORT:-8080}"
IMAGE="aion2-tracker:latest"
CONTAINER="aion2-tracker"

# Character identity. Override by exporting before running the script.
AION2_REGION="${AION2_REGION:-eu}"
AION2_SERVER_ID="${AION2_SERVER_ID:-1302}"
AION2_CHARACTER_ID="${AION2_CHARACTER_ID:-5Ld-L4slCNU8JB2OIV-C-ehrKjJevX4KUri3vfirCBU%3D}"
AION2_CHARACTER_NAME="${AION2_CHARACTER_NAME:-Epitet}"
TZ_VALUE="${TZ_VALUE:-Europe/Bucharest}"

say()  { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
ok()   { printf '    \033[0;32m%s\033[0m\n' "$*"; }
warn() { printf '    \033[0;33m%s\033[0m\n' "$*"; }
die()  { printf '\n\033[0;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- preflight

say "Preflight"

command -v docker >/dev/null 2>&1 || die "docker not found. Is this an Unraid server?"
docker info >/dev/null 2>&1 || die "docker daemon not responding."
ok "docker $(docker version --format '{{.Server.Version}}' 2>/dev/null || echo '?')"

command -v git >/dev/null 2>&1 || die "git not found. Install the Nerd Tools plugin, or use the image-transfer route in docs/deploy-unraid.md."
ok "git $(git --version | awk '{print $3}')"

# Unraid does not ship Compose; it comes from the Docker Compose Manager plugin.
COMPOSE=""
if docker compose version >/dev/null 2>&1; then
  COMPOSE="docker compose"
  ok "docker compose $(docker compose version --short 2>/dev/null || echo '')"
elif command -v docker-compose >/dev/null 2>&1; then
  COMPOSE="docker-compose"
  ok "docker-compose $(docker-compose version --short 2>/dev/null || echo '') (v1)"
else
  warn "No docker compose found. Falling back to plain 'docker run'."
  warn "For compose support install 'Docker Compose Manager' from Community Applications."
fi

[ -d /mnt/user ] || die "/mnt/user not found. Is the array started?"

# Our own container holding the port is not a conflict -- it is the thing we
# are about to replace. Checking the port before removing it made every
# re-run of this script fail on an existing deployment.
port_owner=""
if docker ps --filter "name=^${CONTAINER}$" --format '{{.Ports}}' 2>/dev/null      | grep -q ":${HOST_PORT}->"; then
  port_owner="$CONTAINER"
fi

if [ -n "$port_owner" ]; then
  ok "port ${HOST_PORT} held by the existing ${CONTAINER}, which will be replaced"
elif ss -ltn 2>/dev/null | grep -q ":${HOST_PORT} "      || netstat -ltn 2>/dev/null | grep -q ":${HOST_PORT} "; then
  die "Port ${HOST_PORT} is in use by something else. Re-run with: HOST_PORT=8099 bash $0"
else
  ok "port ${HOST_PORT} is free"
fi

# ---------------------------------------------------------------- layout

say "Creating $APPDATA"
mkdir -p "$APPDATA/data"
ok "data directory ready"

# The container runs as uid 1000 and must be able to write the SQLite file.
chown -R 1000:1000 "$APPDATA/data" 2>/dev/null || warn "could not chown data dir, continuing"

# ---------------------------------------------------------------- source

say "Fetching source"
if [ -d "$SRC/.git" ]; then
  ok "checkout exists, pulling"
  git -C "$SRC" pull --ff-only || warn "pull failed (repo may be private again) - using the existing checkout"
else
  git clone --depth 1 "$REPO_URL" "$SRC" \
    || die "clone failed. If the repo is private, make it public briefly or see docs/deploy-unraid.md for the deploy-key route."
  ok "cloned into $SRC"
fi

# ---------------------------------------------------------------- config

say "Environment file"
if [ -f "$ENV_FILE" ]; then
  ok ".env already exists, leaving it alone"
else
  cat > "$ENV_FILE" <<EOF
# Generated by bootstrap-unraid.sh on $(date -Iseconds)

AION2_REGION=${AION2_REGION}
AION2_SERVER_ID=${AION2_SERVER_ID}
# Percent-encoded. Do NOT decode the trailing %3D or PLAYNC returns 404.
AION2_CHARACTER_ID=${AION2_CHARACTER_ID}
AION2_CHARACTER_NAME=${AION2_CHARACTER_NAME}

AION2_RATE_LIMIT_SECONDS=4
AION2_SNAPSHOT_COOLDOWN_MINUTES=20
SNAPSHOT_INTERVAL_HOURS=6

AION2_DB_PATH=/data/aion2.db
AION2_CONFIG_DIR=/app/config
AION2_PROJECT_ROOT=/app
AION2_HOST=0.0.0.0
AION2_PORT=8080

MCP_AUTH_TOKEN=
TZ=${TZ_VALUE}
EOF
  chmod 600 "$ENV_FILE"
  ok "wrote $ENV_FILE"
fi

# ---------------------------------------------------------------- build/run

say "Building and starting"
cd "$SRC"
docker rm -f "$CONTAINER" >/dev/null 2>&1 || true

if [ -n "$COMPOSE" ]; then
  # Both -f flags matter: the first sets the project directory to the repo
  # root, which is what makes .env and ./config resolve.
  $COMPOSE -f docker-compose.yml -f deploy/unraid.override.yml up -d --build
  ok "started via compose"
else
  docker build -t "$IMAGE" "$SRC"
  docker run -d --name "$CONTAINER" --restart unless-stopped \
    -p "${HOST_PORT}:8080" \
    --env-file "$ENV_FILE" \
    -v "$APPDATA/data:/data" \
    -v "$SRC/config:/app/config:ro" \
    -l net.unraid.docker.webui="http://[IP]:[PORT:8080]/" \
    "$IMAGE"
  ok "started via docker run"
fi

# ---------------------------------------------------------------- verify

say "Waiting for health"
for _ in $(seq 1 40); do
  if curl -fsS "http://localhost:${HOST_PORT}/health" >/dev/null 2>&1; then break; fi
  sleep 3
done

HEALTH="$(curl -fsS "http://localhost:${HOST_PORT}/health" 2>/dev/null || echo '')"
[ -n "$HEALTH" ] || die "service did not come up. Check: docker logs $CONTAINER"
echo "    $HEALTH"

case "$HEALTH" in
  *'"thresholds_loaded":true'*) ok "thresholds loaded" ;;
  *) warn "thresholds NOT loaded - recommendations will be poorly ranked. Check the ./config mount." ;;
esac

# ---------------------------------------------------------------- snapshot

say "First snapshot (about 30 rate-limited requests, ~2 minutes)"
if docker exec "$CONTAINER" python -m aion2 snapshot; then
  ok "snapshot stored"
else
  warn "snapshot failed. Check the character id in $ENV_FILE and: docker logs $CONTAINER"
fi

# ---------------------------------------------------------------- done

IP="$(ip -4 addr show br0 2>/dev/null | awk '/inet /{print $2}' | cut -d/ -f1 | head -1)"
[ -n "$IP" ] || IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
[ -n "$IP" ] || IP="192.168.100.30"

say "Done"
echo "    Dashboard:  http://${IP}:${HOST_PORT}"
echo "    Health:     http://${IP}:${HOST_PORT}/health"
echo "    Logs:       docker logs -f ${CONTAINER}"
echo "    Snapshot:   docker exec ${CONTAINER} python -m aion2 snapshot"
echo "    Audit:      docker exec ${CONTAINER} python -m aion2 audit"
echo ""
echo "    You can set the GitHub repo back to private now."
echo "    Note: 'git pull' in ${SRC} will stop working once it is private."
echo ""
